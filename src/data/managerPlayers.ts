function era(
  id: string,
  label: string,
  seasons: string,
  team: string,
  offense: number,
  defense: number,
  playmaking: number,
  rebounding: number,
  athleticism: number,
  clutch: number,
  aura: number,
  summary: string
): EraAbility {
  return { id, label, seasons, team, offense, defense, playmaking, rebounding, athleticism, clutch, aura, summary };
}

function slug(value: string) {
  return value.toLowerCase().replace(/[.']/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function clamp(value: number) {
  return Math.max(45, Math.min(100, Math.round(value)));
}

function primaryPosition(position: string) {
  if (position.includes("PG")) return "PG";
  if (position.includes("SG")) return "SG";
  if (position.includes("SF")) return "SF";
  if (position.includes("PF")) return "PF";
  if (position.includes("C")) return "C";
  return "SF";
}

function createBaseCard(name: string, index: number): PlayerCard {
  const existing = allPlayers.find((player) => player.name === name);
  if (existing) return existing;

  const positionCycle = ["PG", "SG", "SF", "PF", "C"];
  const position = positionCycle[index % positionCycle.length];
  const debateTier = Math.max(52, 94 - Math.floor(index / 6));

  return {
    id: `manager-${slug(name)}`,
    name,
    aliases: curatedAliases[name],
    teamSide: "legend",
    era: index < 80 ? "历史争议核心" : index < 190 ? "全明星争议池" : "角色/国际争议池",
    position,
    rankSource: {
      rank: index + 1,
      label: "经理模式 300 人争议球星池",
      url: "https://www.basketball-reference.com/players/"
    },
    summaryTags: [debateTier >= 88 ? "历史级讨论" : debateTier >= 75 ? "全明星争议" : "经理模式深池", position, `热度 ${debateTier}`],
    honors: {
      championships: index < 30 ? Math.max(0, 5 - (index % 6)) : index % 27 === 0 ? 1 : 0,
      mvps: index < 20 ? Math.max(0, 4 - (index % 5)) : 0,
      finalsMvps: index < 24 ? (index % 4 === 0 ? 2 : index % 5 === 0 ? 1 : 0) : 0,
      allStars: Math.max(0, Math.round((debateTier - 50) / 4)),
      allNba: Math.max(0, Math.round((debateTier - 58) / 6)),
      allDefense: position === "C" || position === "PF" ? Math.max(0, Math.round((debateTier - 70) / 8)) : index % 9 === 0 ? 1 : 0,
      scoringTitles: position === "SG" && index < 80 ? index % 6 === 0 ? 2 : 0 : 0,
      assistTitles: position === "PG" && index < 90 ? index % 7 === 0 ? 2 : 0 : 0,
      reboundTitles: position === "C" && index < 90 ? index % 6 === 0 ? 2 : 0 : 0,
      dpoy: (position === "C" || position === "PF") && index % 34 === 0 ? 1 : 0,
      roy: index % 41 === 0 ? 1 : 0,
      hallOfFame: index < 95 ? 1 : 0,
      nba75: index < 70 ? 1 : 0
    },
    careerTotals: {
      games: null,
      points: null,
      rebounds: null,
      assists: null,
      steals: null,
      blocks: null,
      ppg: null,
      rpg: null,
      apg: null,
      playoffPoints: null,
      playoffRebounds: null,
      playoffAssists: null
    },
    advanced: {
      dangerLevel: debateTier,
      clutch: clamp(debateTier + (index % 7) - 3),
      legacy: debateTier,
      celticsAura: clamp(debateTier - 8)
    },
    mediaNotes: ["经理模式使用静态争议球星池，能力为游戏化快照。"],
    sourceUrls: ["https://www.basketball-reference.com/players/"],
    trashTalkLines: [`${name} 把自己的巅峰版本抽上桌，经理席开始安静。`]
  };
}

function createGeneratedEras(card: PlayerCard, index: number): EraAbility[] {
  const profile = positionProfiles[primaryPosition(card.position)];
  const legacyBoost = Math.round((card.advanced.legacy - 75) / 3);
  const dangerBoost = Math.round((card.advanced.dangerLevel - 75) / 4);
  const base = {
    offense: clamp(profile.offense + legacyBoost),
    defense: clamp(profile.defense + dangerBoost + card.honors.allDefense),
    playmaking: clamp(profile.playmaking + Math.round(card.honors.assistTitles * 2)),
    rebounding: clamp(profile.rebounding + Math.round(card.honors.reboundTitles * 2)),
    athleticism: clamp(profile.athleticism + (index % 9) - 4),
    clutch: clamp(profile.clutch + Math.round(card.honors.finalsMvps * 2) + (index % 5) - 2),
    aura: clamp(profile.aura + Math.round(card.honors.mvps * 2) + Math.round(card.honors.championships * 1.4))
  };

  return [
    era(
      `${card.id}-rise`,
      "上升期冲击版",
      "早期",
      "Prime path",
      base.offense - 3,
      base.defense - 2,
      base.playmaking - 2,
      base.rebounding - 1,
      base.athleticism + 4,
      base.clutch - 2,
      base.aura - 3,
      "更依赖运动能力和单点爆发。"
    ),
    era(
      `${card.id}-prime`,
      "巅峰统治版",
      "巅峰",
      "Prime path",
      base.offense + 4,
      base.defense + 3,
      base.playmaking + 2,
      base.rebounding + 2,
      base.athleticism + 1,
      base.clutch + 3,
      base.aura + 4,
      "能力最完整、对抗最强的时期。"
    ),
    era(
      `${card.id}-late`,
      "老练季后赛版",
      "后期",
      "Veteran path",
      base.offense,
      base.defense,
      base.playmaking + 4,
      base.rebounding,
      base.athleticism - 5,
      base.clutch + 5,
      base.aura + 2,
      "运动能力下降，但经验和关键回合更稳。"
    )
  ].map((item) => ({
    ...item,
    offense: clamp(item.offense),
    defense: clamp(item.defense),
    playmaking: clamp(item.playmaking),
    rebounding: clamp(item.rebounding),
    athleticism: clamp(item.athleticism),
    clutch: clamp(item.clutch),
    aura: clamp(item.aura)
  }));
}

const uniqueNames = [...new Set(debateNames)].slice(0, 300);

export const managerPlayers: ManagerPlayer[] = uniqueNames.map((name, index) => {
  const baseCard = createBaseCard(name, index);
  return {
    ...baseCard,
    aliases: [...(baseCard.aliases ?? []), ...(curatedAliases[name] ?? [])],
    debateRank: index + 1,
    eras: curatedEras[name] ?? createGeneratedEras(baseCard, index)
  };
});

export function getManagerPlayerDisplayName(player: ManagerPlayer) {
  return chineseNamesByEnglishName[player.name] ?? player.name;
}
